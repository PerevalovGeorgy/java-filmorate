CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    login VARCHAR(255) NOT NULL UNIQUE,
    name VARCHAR(255),
    birthday DATE
);


CREATE TABLE IF NOT EXISTS FriendshipStatus (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS friendships (
    idUser INTEGER NOT NULL,
    idFriends INTEGER NOT NULL,
    friendshipStatus_id INTEGER NOT NULL,
    PRIMARY KEY (idUser, idFriends),
    FOREIGN KEY (idUser) REFERENCES users(id) ON DELETE CASCADE,
    FOREIGN KEY (idFriends) REFERENCES users(id) ON DELETE CASCADE,
    FOREIGN KEY (friendshipStatus_id) REFERENCES FriendshipStatus(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS MpaRating (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mpaRating VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS films (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    description VARCHAR(255),
    releaseDate DATE,
    duration INTEGER,
    mpaRating_id INTEGER,
    FOREIGN KEY (mpaRating_id) REFERENCES MpaRating(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS Genre (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    genre VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS FilmsGenre (
    filmId INTEGER NOT NULL,
    genreId INTEGER NOT NULL,
    PRIMARY KEY (filmId, genreId),
    FOREIGN KEY (filmId) REFERENCES films(id) ON DELETE CASCADE,
    FOREIGN KEY (genreId) REFERENCES Genre(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS filmLikes (
    filmID INTEGER NOT NULL,
    userId INTEGER NOT NULL,
    PRIMARY KEY (filmID, userId),
    FOREIGN KEY (filmID) REFERENCES films(id) ON DELETE CASCADE,
    FOREIGN KEY (userId) REFERENCES users(id) ON DELETE CASCADE
);
